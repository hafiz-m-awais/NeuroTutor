let currentRoadmap = null;

function openRoadmap(topic) {
  document.getElementById('roadmap-panel').classList.add('open');
  if (topic) {
    document.getElementById('roadmap-topic-input').value = topic;
  } else {
    document.getElementById('roadmap-topic-input').focus();
  }
}

function closeRoadmap() {
  document.getElementById('roadmap-panel').classList.remove('open');
}

function setRoadmapTopic(topic) {
  document.getElementById('roadmap-topic-input').value = topic;
  generateRoadmap();
}

async function generateRoadmap() {
  const topic = document.getElementById('roadmap-topic-input').value.trim();
  const days = parseInt(document.getElementById('roadmap-days').value) || 30;
  const level = document.getElementById('roadmap-level').value || 'beginner';

  if (!topic) return;

  const body = document.getElementById('roadmap-body');
  const btn = document.getElementById('roadmap-generate-btn');
  const downloadBtn = document.getElementById('roadmap-download-btn');
  const shareBtn = document.getElementById('roadmap-share-btn');

  btn.disabled = true;
  btn.textContent = 'Generating...';
  downloadBtn.style.display = 'none';
  shareBtn.style.display = 'none';
  currentRoadmap = null;

  body.innerHTML = `<div class="roadmap-loading">
    Generating your ${days}-day ${topic} roadmap...<br><br>
    This may take 15-30 seconds for longer roadmaps.
  </div>`;

  try {
    const res = await fetch('/roadmap', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ topic, days, level })
    });

    const data = await res.json();

    if (!res.ok) {
      body.innerHTML = `<div class="roadmap-loading" style="color:#f44336">${data.error || 'Failed to generate roadmap'}</div>`;
      return;
    }

    currentRoadmap = data;
    renderRoadmap(data);
    downloadBtn.style.display = 'block';
    shareBtn.style.display = 'block';

  } catch (err) {
    body.innerHTML = `<div class="roadmap-loading" style="color:#f44336">Connection error. Please try again.</div>`;
  } finally {
    btn.disabled = false;
    btn.textContent = 'Generate';
  }
}

function renderRoadmap(data) {
  const body = document.getElementById('roadmap-body');

  let html = '';

  if (data.goal) {
    html += `<div class="roadmap-goal">🎯 Goal: ${escapeHtml(data.goal)}</div>`;
  }

  if (data.weeks && data.weeks.length > 0) {
    data.weeks.forEach(week => {
      html += `<div class="week-block">
        <div class="week-title">Week ${week.week}: ${escapeHtml(week.title || '')}</div>`;

      if (week.days && week.days.length > 0) {
        week.days.forEach(day => {
          const tasks = (day.tasks || []).map(t =>
            `<li>${escapeHtml(t)}</li>`
          ).join('');

          html += `<div class="day-card">
            <div class="day-header">
              <div class="day-num">${day.day}</div>
              <div class="day-topic">${escapeHtml(day.topic || '')}</div>
            </div>
            <ul class="day-tasks">${tasks}</ul>
            ${day.resource ? `<span class="day-resource">📚 ${escapeHtml(day.resource)}</span>` : ''}
          </div>`;
        });
      }

      html += '</div>';
    });
  } else {
    html += '<div class="roadmap-loading">No roadmap data generated. Please try again.</div>';
  }

  body.innerHTML = html;
}

function downloadRoadmap() {
  if (!currentRoadmap) return;

  const topic = currentRoadmap.topic || 'roadmap';
  const days = currentRoadmap.days || 30;
  const level = currentRoadmap.level || 'beginner';
  const goal = currentRoadmap.goal || '';

  let text = `${topic.toUpperCase()} — ${days}-Day Learning Roadmap\n`;
  text += `Level: ${level}\n`;
  text += `Goal: ${goal}\n`;
  text += '='.repeat(50) + '\n\n';

  if (currentRoadmap.weeks) {
    currentRoadmap.weeks.forEach(week => {
      text += `WEEK ${week.week}: ${week.title || ''}\n`;
      text += '-'.repeat(30) + '\n';

      if (week.days) {
        week.days.forEach(day => {
          text += `\nDay ${day.day}: ${day.topic || ''}\n`;
          (day.tasks || []).forEach(task => {
            text += `  → ${task}\n`;
          });
          if (day.resource) {
            text += `  📚 Resource: ${day.resource}\n`;
          }
        });
      }
      text += '\n';
    });
  }

  text += '\n---\nGenerated by AskAI Pakistan — Free AI Tutor for Pakistani CS Students\n';
  text += 'huggingface.co/spaces/awaisriaz/askai-pakistan\n';

  const blob = new Blob([text], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${topic.replace(/\s+/g, '_')}_${days}day_roadmap.txt`;
  a.click();
  URL.revokeObjectURL(url);
}

function shareRoadmap() {
  if (!currentRoadmap) return;

  const topic = currentRoadmap.topic || 'roadmap';
  const days = currentRoadmap.days || 30;
  const level = currentRoadmap.level || 'beginner';
  const goal = currentRoadmap.goal || '';

  let fullText = `${topic.toUpperCase()} — ${days}-Day Learning Roadmap\n`;
  fullText += `Level: ${level}\n`;
  fullText += `Goal: ${goal}\n`;
  fullText += '='.repeat(50) + '\n\n';

  if (currentRoadmap.weeks) {
    currentRoadmap.weeks.forEach(week => {
      fullText += `WEEK ${week.week}: ${week.title || ''}\n`;
      fullText += '-'.repeat(30) + '\n';
      if (week.days) {
        week.days.forEach(day => {
          fullText += `\nDay ${day.day}: ${day.topic || ''}\n`;
          (day.tasks || []).forEach(task => {
            fullText += `  → ${task}\n`;
          });
          if (day.resource) {
            fullText += `  📚 Resource: ${day.resource}\n`;
          }
        });
      }
      fullText += '\n';
    });
  }

  fullText += '\n---\nGenerated by AskAI Pakistan — Free AI Tutor for Pakistani CS Students\n';
  fullText += 'huggingface.co/spaces/awaisriaz/askai-pakistan\n';

  const shortText = `I just generated a ${days}-day ${topic} learning roadmap using AskAI Pakistan! 🚀\n\nFree AI tutor for Pakistani CS students:\nhuggingface.co/spaces/awaisriaz/askai-pakistan`;

  const fileName = `${topic.replace(/\s+/g, '_')}_${days}day_roadmap.txt`;
  const file = new File([fullText], fileName, { type: 'text/plain' });

  const shareData = {
    title: 'My Learning Roadmap',
    text: shortText
  };

  // If the browser supports sharing files, attach the text file.
  if (navigator.canShare && navigator.canShare({ files: [file] })) {
    shareData.files = [file];
  } else {
    // If files aren't supported, include the entire roadmap in the text body
    shareData.text = shortText + "\n\n" + fullText;
  }

  const fallbackCopy = () => {
    navigator.clipboard.writeText(fullText).then(() => {
      const btn = document.getElementById('roadmap-share-btn');
      btn.textContent = 'Copied Full Roadmap!';
      setTimeout(() => btn.textContent = '📤 Share', 3000);
    }).catch(err => console.error("Clipboard copy failed: ", err));
  };

  if (navigator.share) {
    navigator.share(shareData)
      .catch((err) => {
        console.warn("Share failed or was canceled, falling back to clipboard...", err);
        if (err.name !== 'AbortError') {
          fallbackCopy();
        }
      });
  } else {
    fallbackCopy();
  }
}

document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') closeRoadmap();
});