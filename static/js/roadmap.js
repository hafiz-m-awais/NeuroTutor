let currentRoadmap = null;

function openRoadmap(topic) {
  document.getElementById('roadmap-panel').classList.add('open');
  if (topic) {
    document.getElementById('roadmap-topic-input').value = topic;
  } else {
    document.getElementById('roadmap-topic-input').focus();
  }
}

function closeRoadmap() {
  document.getElementById('roadmap-panel').classList.remove('open');
}

function setRoadmapTopic(topic) {
  document.getElementById('roadmap-topic-input').value = topic;
  generateRoadmap();
}

async function generateRoadmap() {
  const topic = document.getElementById('roadmap-topic-input').value.trim();
  const days = parseInt(document.getElementById('roadmap-days').value) || 30;
  const level = document.getElementById('roadmap-level').value || 'beginner';

  if (!topic) return;

  const body = document.getElementById('roadmap-body');
  const btn = document.getElementById('roadmap-generate-btn');
  const downloadBtn = document.getElementById('roadmap-download-btn');
  const shareBtn = document.getElementById('roadmap-share-btn');

  btn.disabled = true;
  btn.textContent = 'Generating...';
  downloadBtn.style.display = 'none';
  shareBtn.style.display = 'none';
  currentRoadmap = null;

  body.innerHTML = `<div class="roadmap-loading">
    Generating your ${days}-day ${topic} roadmap...<br><br>
    This may take 15-30 seconds for longer roadmaps.
  </div>`;

  try {
    const res = await fetch('/roadmap', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ topic, days, level })
    });

    const data = await res.json();

    if (!res.ok) {
      body.innerHTML = `<div class="roadmap-loading" style="color:#f44336">${data.error || 'Failed to generate roadmap'}</div>`;
      return;
    }

    currentRoadmap = data;
    renderRoadmap(data);
    downloadBtn.style.display = 'block';
    shareBtn.style.display = 'block';

  } catch (err) {
    body.innerHTML = `<div class="roadmap-loading" style="color:#f44336">Connection error. Please try again.</div>`;
  } finally {
    btn.disabled = false;
    btn.textContent = 'Generate';
  }
}

function renderRoadmap(data) {
  const body = document.getElementById('roadmap-body');

  let html = '';

  if (data.goal) {
    html += `<div class="roadmap-goal">🎯 Goal: ${escapeHtml(data.goal)}</div>`;
  }

  if (data.weeks && data.weeks.length > 0) {
    data.weeks.forEach(week => {
      html += `<div class="week-block">
        <div class="week-title">Week ${week.week}: ${escapeHtml(week.title || '')}</div>`;

      if (week.days && week.days.length > 0) {
        week.days.forEach(day => {
          const tasks = (day.tasks || []).map(t =>
            `<li>${escapeHtml(t)}</li>`
          ).join('');

          html += `<div class="day-card">
            <div class="day-header">
              <div class="day-num">${day.day}</div>
              <div class="day-topic">${escapeHtml(day.topic || '')}</div>
            </div>
            <ul class="day-tasks">${tasks}</ul>
            ${day.resource ? `<span class="day-resource">📚 ${escapeHtml(day.resource)}</span>` : ''}
          </div>`;
        });
      }

      html += '</div>';
    });
  } else {
    html += '<div class="roadmap-loading">No roadmap data generated. Please try again.</div>';
  }

  body.innerHTML = html;
}

function getRoadmapExportContent(format) {
  const topic = currentRoadmap.topic || 'roadmap';
  const days = currentRoadmap.days || 30;
  const level = currentRoadmap.level || 'beginner';
  const goal = currentRoadmap.goal || '';

  let content = '';
  let mimeType = 'text/plain';
  let ext = format;

  if (format === 'json') {
    content = JSON.stringify(currentRoadmap, null, 2);
    mimeType = 'application/json';
  } else if (format === 'md') {
    content = `# ${topic.toUpperCase()} — ${days}-Day Learning Roadmap\n\n`;
    content += `**Level:** ${level}  \n**Goal:** ${goal}\n\n---\n\n`;

    if (currentRoadmap.weeks) {
      currentRoadmap.weeks.forEach(week => {
        content += `## WEEK ${week.week}: ${week.title || ''}\n\n`;
        if (week.days) {
          week.days.forEach(day => {
            content += `### Day ${day.day}: ${day.topic || ''}\n`;
            (day.tasks || []).forEach(task => {
              content += `- ${task}\n`;
            });
            if (day.resource) {
              content += `> 📚 **Resource:** ${day.resource}\n`;
            }
            content += '\n';
          });
        }
      });
    }
    content += '\n---\n*Generated by AskAI Pakistan — Free AI Tutor for Pakistani CS Students*\n[huggingface.co/spaces/awaisriaz/askai-pakistan](https://huggingface.co/spaces/awaisriaz/askai-pakistan)\n';
    mimeType = 'text/markdown';
  } else {
    // defaults to txt
    content = `${topic.toUpperCase()} — ${days}-Day Learning Roadmap\n`;
    content += `Level: ${level}\n`;
    content += `Goal: ${goal}\n`;
    content += '='.repeat(50) + '\n\n';

    if (currentRoadmap.weeks) {
      currentRoadmap.weeks.forEach(week => {
        content += `WEEK ${week.week}: ${week.title || ''}\n`;
        content += '-'.repeat(30) + '\n';
        if (week.days) {
          week.days.forEach(day => {
            content += `\nDay ${day.day}: ${day.topic || ''}\n`;
            (day.tasks || []).forEach(task => {
              content += `  → ${task}\n`;
            });
            if (day.resource) {
              content += `  📚 Resource: ${day.resource}\n`;
            }
          });
        }
        content += '\n';
      });
    }
    content += '\n---\nGenerated by AskAI Pakistan — Free AI Tutor for Pakistani CS Students\n';
    content += 'huggingface.co/spaces/awaisriaz/askai-pakistan\n';
  }

  if (format === 'pdf') {
    mimeType = 'application/pdf';
  }

  return {
    content,
    mimeType,
    fileName: `${topic.replace(/\s+/g, '_')}_${days}day_roadmap.${ext}`
  };
}

function downloadRoadmap() {
  if (!currentRoadmap) return;

  const selector = document.getElementById('roadmap-format-select');
  const format = selector ? selector.value : 'txt';

  const exportData = getRoadmapExportContent(format);

  if (format === 'pdf') {
    const element = document.getElementById('roadmap-body');
    const opt = {
      margin: 10,
      filename: exportData.fileName,
      image: { type: 'jpeg', quality: 0.98 },
      html2canvas: { scale: 2, useCORS: true },
      jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' }
    };
    html2pdf().set(opt).from(element).save();
    return;
  }

  const blob = new Blob([exportData.content], { type: exportData.mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = exportData.fileName;
  a.click();
  URL.revokeObjectURL(url);
}

function shareRoadmap() {
  if (!currentRoadmap) return;

  const topic = currentRoadmap.topic || 'roadmap';
  const days = currentRoadmap.days || 30;

  const selector = document.getElementById('roadmap-format-select');
  const format = selector ? selector.value : 'txt';
  const exportData = getRoadmapExportContent(format);

  const shortText = `I just generated a ${days}-day ${topic} learning roadmap using AskAI Pakistan! 🚀\n\nFree AI tutor for Pakistani CS students:\nhuggingface.co/spaces/awaisriaz/askai-pakistan`;

  const performShare = (fileBlob, fileObj) => {
    const shareData = {
      title: 'My Learning Roadmap',
      text: shortText
    };

    if (navigator.canShare && navigator.canShare({ files: [fileObj] })) {
      shareData.files = [fileObj];
    } else if (format !== 'pdf') {
      shareData.text = shortText + "\n\n" + exportData.content;
    } // Cannot append PDF to text cleanly so we stick to the short description

    const fallbackCopy = () => {
      // PDF can't be copied to clipboard as text
      const contentToCopy = format === 'pdf' ? shortText : exportData.content;
      navigator.clipboard.writeText(contentToCopy).then(() => {
        const btn = document.getElementById('roadmap-share-btn');
        btn.textContent = format === 'pdf' ? 'Copied Link!' : 'Copied Full Roadmap!';
        setTimeout(() => btn.textContent = '📤 Share', 3000);
      }).catch(err => console.error("Clipboard copy failed: ", err));
    };

    if (navigator.share) {
      navigator.share(shareData)
        .catch((err) => {
          console.warn("Share failed or was canceled, falling back to clipboard...", err);
          if (err.name !== 'AbortError') {
            fallbackCopy();
          }
        });
    } else {
      fallbackCopy();
    }
  };

  if (format === 'pdf') {
    const element = document.getElementById('roadmap-body');
    const opt = {
      margin: 10,
      filename: exportData.fileName,
      image: { type: 'jpeg', quality: 0.98 },
      html2canvas: { scale: 2, useCORS: true },
      jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' }
    };
    html2pdf().set(opt).from(element).output('blob').then(blob => {
      const file = new File([blob], exportData.fileName, { type: 'application/pdf' });
      performShare(blob, file);
    });
  } else {
    const file = new File([exportData.content], exportData.fileName, { type: exportData.mimeType });
    performShare(null, file);
  }
}

document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') closeRoadmap();
});